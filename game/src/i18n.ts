export type I18nKey = keyof typeof strings.en;

export function t(key: I18nKey): string {
  return (strings[lang] as Record<string, string>)[key] ?? strings.en[key];
}

export function getLang(): 'en' | 'tr' { return lang; }

export function tFmt(key: I18nKey, vars: Record<string, string | number>): string {
  let s = t(key);
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
